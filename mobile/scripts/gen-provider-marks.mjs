// Writes src/lib/provider-marks.ts from the desktop's provider marks (../src/assets), so the
// phone draws the same logos. Monochrome marks take the text colour (`currentColor`).
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.dirname(path.dirname(new URL(import.meta.url).pathname));
const assets = path.join(root, "..", "src", "assets");
const marks = {
  claude: ["providers/claude.svg", false],
  codex: ["models/openai.svg", true],
  cursor: ["providers/cursor.svg", true],
  opencode: ["providers/opencode.svg", true],
  grok: ["providers/grok.svg", true],
  antigravity: ["providers/antigravity.svg", false],
  droid: ["providers/droid.svg", true],
  pi: ["providers/pi.svg", false],
  devin: ["providers/devin.svg", true],
  hermes: ["providers/hermes.svg", true],
};
const lines = ["// Generated by scripts/gen-provider-marks.mjs from the desktop's marks; do not edit.", "export const PROVIDER_MARKS: Record<string, { readonly xml: string; readonly monochrome: boolean }> = {"];
for (const [id, [file, monochrome]] of Object.entries(marks)) {
  let xml = readFileSync(path.join(assets, file), "utf8").replace(/<\?xml[^>]*>/, "").replace(/<!--[\s\S]*?-->/g, "").replace(/\s+/g, " ").trim();
  if (monochrome) xml = xml.replace(/fill="(?!none)[^"]*"/g, 'fill="currentColor"').replace(/<svg /, '<svg fill="currentColor" ');
  lines.push(`  ${id}: { monochrome: ${monochrome}, xml: ${JSON.stringify(xml)} },`);
}
lines.push("};", "");
writeFileSync(path.join(root, "src", "lib", "provider-marks.ts"), lines.join("\n"));
console.log("provider marks written");
